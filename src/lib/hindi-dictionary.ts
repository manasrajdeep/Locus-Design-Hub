/** Regex rules for generated strings (dates, areas, counts). */
const patternRules: { re: RegExp; to: (m: RegExpMatchArray) => string }[] = [
  {
    re: /^(\d{1,2}) (Jan|Feb|Mar|Apr|May|Jun|Jul|Aug|Sep|Oct|Nov|Dec)[a-z]* (\d{4})$/,
    to: (m) => `${m[1]} ${HI_MONTHS[m[2].toLowerCase()]} ${m[3]}`,
  },
  { re: /^([\d.,]+)\s*sq\s*ft$/i, to: (m) => `${m[1]} वर्ग फुट` },
  { re: /^(₹\s?[\d.,]+)\s*Cr$/i, to: (m) => `${m[1]} करोड़` },
  { re: /^(₹\s?[\d.,]+)\s*L$/i, to: (m) => `${m[1]} लाख` },
  { re: /^Stage (\d+) of (\d+)$/i, to: (m) => `चरण ${m[1]} / ${m[2]}` },
  { re: /^Show all \((\d+)\)$/i, to: (m) => `सभी दिखाएँ (${m[1]})` },
  { re: /^(\d+) new documents$/i, to: (m) => `${m[1]} नए दस्तावेज़` },
  { re: /^(\d+) new site photos$/i, to: (m) => `${m[1]} नई साइट फ़ोटो` },
  { re: /^(\d+) actions completed$/i, to: (m) => `${m[1]} कार्य पूर्ण` },
  { re: /^(\d+)\/(\d+) stages$/i, to: (m) => `${m[1]}/${m[2]} चरण` },
  { re: /^Stage (\d+) of (\d+) — (.+)$/i, to: (m) => `चरण ${m[1]} / ${m[2]} — ${m[3]}` },
  { re: /^Now on (.+)$/i, to: (m) => `अब ${m[1]} पर` },
];

const collapse = (s: string) => s.replace(/\s+/g, " ").trim();

export function toHindi(raw: string): string {
  const text = collapse(raw);
  if (!text) return raw;
  const direct = hindiPhrases[text];
  if (direct) return raw.replace(text, direct);

  // Try without trailing punctuation
  const m = text.match(/^(.*?)([.!?:…]+)$/);
  if (m) {
    const base = hindiPhrases[m[1]];
    if (base) return raw.replace(text, base + m[2]);
  }

  for (const rule of patternRules) {
    const match = text.match(rule.re);
    if (match) return raw.replace(text, rule.to(match));
  }

  const word = hindiWords[text.toLowerCase()];
  if (word) return raw.replace(text, word);

  return raw;
}
